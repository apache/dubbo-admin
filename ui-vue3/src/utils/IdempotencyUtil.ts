type WebCrypto = Crypto & { randomUUID?: () => string }

/**
 * Generates a client-side idempotency key.
 *
 * `crypto.randomUUID` only exists in secure contexts, so a deployment served
 * over plain HTTP from a non-localhost address (for example a Kubernetes
 * NodePort) must still be able to send chat messages. Fall back to
 * `getRandomValues`, which is available in insecure contexts, and finally to
 * a time/random pair.
 */
export const generateIdempotencyKey = (): string => {
  const webCrypto = typeof globalThis.crypto === 'undefined' ? undefined : (globalThis.crypto as WebCrypto)
  if (webCrypto && typeof webCrypto.randomUUID === 'function') {
    return webCrypto.randomUUID()
  }
  if (webCrypto && typeof webCrypto.getRandomValues === 'function') {
    const bytes = webCrypto.getRandomValues(new Uint8Array(16))
    // RFC 4122 version 4 and variant bits.
    bytes[6] = (bytes[6] & 0x0f) | 0x40
    bytes[8] = (bytes[8] & 0x3f) | 0x80
    const hex = Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('')
    return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
  }
  return `${Date.now().toString(16)}-${Math.random().toString(16).slice(2)}`
}
