package logger

// LoggerSpec defines logger configuration
type LoggerSpec struct {
	Level string `yaml:"level"`
}

// DefaultLoggerSpec returns default logger configuration
func DefaultLoggerSpec() *LoggerSpec {
	return &LoggerSpec{
		Level: "info",
	}
}
